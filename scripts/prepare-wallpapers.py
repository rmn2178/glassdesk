"""Build offline thumbnails and integrity metadata; never embed full images.

Run from any directory. Requires Pillow, as do the other image asset scripts.
Use --import-directory PATH to append JPEGs without changing existing IDs.
"""
import argparse
import hashlib
import io
import json
import shutil
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ORIGINALS = ROOT / "apps/settings/wallpapers"
PREVIEWS = ROOT / "apps/settings/src/assets/wallpapers"
CATALOG = ROOT / "apps/settings/src/wallpaper-catalog.ts"
LIMIT = 32 * 1024 * 1024


def originals():
    return sorted(ORIGINALS.glob("desktop-[0-9][0-9].jpg"))


def import_images(directory):
    files = originals()
    hashes = {hashlib.sha256(p.read_bytes()).digest() for p in files}
    next_id = len(files) + 1
    for source in sorted(directory.iterdir()):
        if not source.is_file() or source.suffix.lower() not in {".jpg", ".jpeg"}:
            continue
        if not 0 < source.stat().st_size <= LIMIT:
            raise ValueError(f"Original size out of bounds: {source.name}")
        data = source.read_bytes()
        digest = hashlib.sha256(data).digest()
        if digest in hashes:
            continue
        with Image.open(io.BytesIO(data)) as image:
            if image.format != "JPEG" or image.width * image.height > 40_000_000:
                raise ValueError(f"Unsupported original: {source.name}")
            image.verify()
        if next_id > 99:
            raise ValueError("Wallpaper catalog limit exceeded")
        destination = ORIGINALS / f"desktop-{next_id:02}.jpg"
        if destination.exists():
            raise ValueError(f"Refusing to replace {destination.name}")
        shutil.copyfile(source, destination)
        hashes.add(digest)
        print(f"{source.name} -> {destination.name}")
        next_id += 1


def generate(check):
    records, imports, entries = [], [], []
    changes = []

    def output(path, data):
        if path.exists() and path.read_bytes() == data:
            return
        changes.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

    files = originals()
    if not files:
        raise ValueError("The wallpaper catalog cannot be empty")
    previous = {row['id']: row for row in json.loads((ORIGINALS / 'catalog.json').read_text())} if (ORIGINALS / 'catalog.json').exists() else {}
    for index, source in enumerate(files, 1):
        if source.name != f"desktop-{index:02}.jpg":
            raise ValueError("Original IDs must be contiguous; append, never renumber")
        if not 0 < source.stat().st_size <= LIMIT:
            raise ValueError(f"Original size out of bounds: {source.name}")
        data = source.read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if index in previous and previous[index]['sha256'] != digest:
            raise ValueError(f"Append a new ID instead of changing a published original: {source.name}")
        with Image.open(io.BytesIO(data)) as image:
            if image.format != "JPEG" or image.width * image.height > 40_000_000:
                raise ValueError(f"Unsupported original: {source.name}")
            preview = ImageOps.exif_transpose(image).convert("RGB")
            width, height = preview.size
            preview.thumbnail((400, 400), Image.Resampling.LANCZOS)
            encoded = io.BytesIO()
            preview.save(encoded, "JPEG", quality=82, optimize=True, progressive=True)
            output(PREVIEWS / source.name, encoded.getvalue())
            records.append({"id": index, "name": source.name, "bytes": len(data),
                            "sha256": digest,
                            "width": width, "height": height})
            imports.append(f'import preview{index} from "./assets/wallpapers/{source.name}";')
            entries.append(f"  {{ id: {index}, preview: preview{index}, width: {preview.width}, height: {preview.height} }},")
    output(ORIGINALS / "catalog.json", (json.dumps(records, indent=2) + "\n").encode())
    text = "// Generated by scripts/prepare-wallpapers.py. Only these small previews are bundled.\n"
    text += "\n".join(imports) + "\n\nexport const WALLPAPERS = [\n" + "\n".join(entries) + "\n] as const;\n"
    output(CATALOG, text.encode())
    print(f"{len(records)} originals: {sum(r['bytes'] for r in records):,} bytes; previews: "
          f"{sum(p.stat().st_size for p in PREVIEWS.glob('*.jpg')):,} bytes")
    if check and changes:
        raise SystemExit("Regenerate wallpaper assets: " + ", ".join(map(str, changes)))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--import-directory", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.import_directory:
        if args.check:
            parser.error("--check cannot import files")
        import_images(args.import_directory)
    generate(args.check)
